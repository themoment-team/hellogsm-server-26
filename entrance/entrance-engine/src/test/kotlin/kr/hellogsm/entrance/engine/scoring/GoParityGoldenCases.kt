/** 성취도 환산점수(5=A … 1=E) → Achievement */
private fun ach(vararg points: Int): List<Achievement> = points.map {
    when (it) {
        5 -> Achievement.A
        4 -> Achievement.B
        3 -> Achievement.C
        2 -> Achievement.D
        1 -> Achievement.E
        else -> error("유효하지 않은 성취도 환산점수: $it")
    }
}

